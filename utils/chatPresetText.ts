/** 換名字：只換 {{char}}、{{user}} 兩個（大小寫照 ST 不分）；一次換完，名字裡有大括號也不會再被換 */
export const fillChatNames = (text: string, charName: string, userName: string): string =>
    text.replace(/\{\{(char|user)\}\}/gi, (_, key: string) => (key.toLowerCase() === 'char' ? charName : userName));


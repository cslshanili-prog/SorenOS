const PERSONALITY_GROUPS: Record<string, string[]> = {
    hot:    ['熱情', '外向', '活潑'],
    cool:   ['冷靜', '內斂', '理性'],
    kind:   ['善良', '溫柔', '包容'],
    wild:   ['暴躁', '直率', '衝動'],
    dark:   ['腹黑', '聰明', '神秘'],
    tsun:   ['傲嬌', '要強', '敏感'],
    chill:  ['懶散', '隨和', '樂天'],
    pure:   ['單純', '可愛', '活潑'],
    strict: ['嚴肅', '負責', '完美主義'],
};

function getPersonalityGroup(personality: string[]): string {
    for (const [group, traits] of Object.entries(PERSONALITY_GROUPS)) {
        if (personality.some(p => traits.some(t => equalsAnyScript(t, p)))) return group;
    }
    return 'chill';
}


/**
 * 「現在幾點」後面跟的那句語境框定 —— 純常量零依賴，瀏覽器與 Cloudflare Worker
 * 共用同一份（同 utils/scheduleChangeParse.ts 的路子）。
 *
 * 為什麼需要它：報時那一段貼在生成點前、注意力最強的位置，而人設躺在幾千字之外。
 * 光給一句「現在是深夜 23:47」，模型每輪都會把話題收到「快睡吧、明天見」上，聊到
 * 哪都一樣，像撞上了健康提醒。這句話把時間的作用限定回「背景」：影響語氣和狀態，
 * 但不決定這段對話該不該結束。
 *
 * 寫法全正向：只說時間該起什麼作用，不點名任何要避開的話術——禁語寫進提示詞反而
 * 會激活它。
 *
 * 只在真的有人在對話時給。日程生成、歌單、攻略、手冊、小劇場、角色間對話、以及
 * 「到點主動找人說話」的主動消息，都走各自的時間注入，但那些場合沒有「對方」在這個
 * 點跟角色說話，末句會變成擺在注意力最強位置上的一句假話。
 */

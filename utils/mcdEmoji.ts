/**
 * 麥當勞商品名 → 大 emoji 映射
 * MCP 上游不返圖, 用關鍵詞匹配給每條菜單貼一個像樣的圖標, 比 🍔 通殺好看。
 * 順序敏感: 越具體的關鍵詞越往前。
 */

const RULES: Array<[RegExp, string]> = [
    // 早餐
    [/[麦麥][满滿]分|帕尼尼|[松鬆][饼餅]/i, '🥞'],
    [/[猪豬]柳|火腿|培根扒/i, '🥓'],
    // 主食類
    [/[鳕鱈][鱼魚]|深海[鱼魚]|[鱼魚]柳/i, '🐟'],
    [/[鸡雞]翅/i, '🍗'],
    [/[鸡雞]腿|[鸡雞][块塊]|[鸡雞][条條]/i, '🍗'],
    [/[鸡雞]米花|[麦麥][乐樂][鸡雞]/i, '🍿'],
    [/[汉漢]堡|牛堡|安格斯|板[烧燒]|[麦麥]辣|[双雙][层層]|[汉漢]|堡(?![满滿])/i, '🍔'],
    // 配餐
    [/中薯|大薯|小薯|薯(?!片)/i, '🍟'],
    [/玉米杯|玉米/i, '🌽'],
    [/沙拉/i, '🥗'],
    [/派|[苹蘋]果派|香芋派|菠[萝蘿]派/i, '🥧'],
    // 甜品/小吃
    [/[麦麥]旋[风風]|[圣聖]代|冰淇淋|甜筒/i, '🍦'],
    [/巧克力|朱古力/i, '🍫'],
    [/草莓/i, '🍓'],
    [/菠[萝蘿]/i, '🍍'],
    [/曲奇|[奥奧]利[奥奧]|[饼餅][干乾]/i, '🍪'],
    // 飲料
    [/咖啡|拿[铁鐵]|美式|卡布奇[诺諾]|摩卡/i, '☕'],
    [/茶|奶茶|[柠檸]檬茶/i, '🧋'],
    [/可[乐樂]|雪碧|芬[达達]|汽水|可可|百事/i, '🥤'],
    [/果汁|橙汁|[苹蘋]果汁/i, '🧃'],
    [/牛奶|酸奶/i, '🥛'],
    // 套餐 (兜底前最後一道, 套餐多半含漢堡)
    [/套餐|超值|全家桶|[双雙]人/i, '🍱'],
];

export const mcdItemEmoji = (name?: string): string => {
    if (!name) return '🍽️';
    for (const [re, em] of RULES) {
        if (re.test(name)) return em;
    }
    return '🍽️';
};

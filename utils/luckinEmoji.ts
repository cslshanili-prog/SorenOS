/**
 * 瑞幸商品名 → 大 emoji 映射
 * MCP 上游不一定返圖, 用關鍵詞匹配給每條菜單貼一個像樣的圖標, 比 ☕ 通殺好看。
 * 順序敏感: 越具體的關鍵詞越往前。
 */

const RULES: Array<[RegExp, string]> = [
    // 招牌 / 生椰 / 厚乳系列
    [/生椰|椰[云雲]|椰子/i, '🥥'],
    [/厚乳|拿[铁鐵]/i, '☕'],
    [/美式|[浓濃][缩縮]|espresso|意式/i, '☕'],
    [/卡布奇[诺諾]|摩卡|[玛瑪]奇朵|馥芮白|flat\s*white/i, '☕'],
    // 茶飲 / 果茶
    [/茶拿[铁鐵]|奶茶|[轻輕]乳茶/i, '🧋'],
    [/茉莉|[乌烏][龙龍]|[红紅]茶|[绿綠]茶|茶(?!拿)/i, '🍵'],
    [/[柠檸]檬|青提|葡萄|橙|柚|莓|桃|芒果|[凤鳳]梨|菠[萝蘿]/i, '🧃'],
    // 巧克力 / 可可
    [/巧克力|可可|布朗尼/i, '🍫'],
    // 冷萃 / 氣泡
    [/冷萃|[气氣]泡|微醺|酒/i, '🫧'],
    // 烘焙 / 輕食
    [/蛋糕|慕斯|提拉米[苏蘇]/i, '🍰'],
    [/可[颂頌]|牛角|[面麵]包|吐司/i, '🥐'],
    [/曲奇|[饼餅][干乾]|司康/i, '🍪'],
    [/三明治|帕尼尼|[轻輕]食|沙拉/i, '🥪'],
    [/蛋[挞撻]|[挞撻]/i, '🥧'],
    // 周邊 / 券
    [/券|卡|[兑兌][换換]|套餐|套票/i, '🎟️'],
    // 兜底: 咖啡店, 默認咖啡杯
];

export const luckinItemEmoji = (name?: string): string => {
    if (!name) return '🥤';
    for (const [re, em] of RULES) {
        if (re.test(name)) return em;
    }
    return '☕';
};
